const { contextBridge, ipcRenderer } = require('electron');

// Ponte mínima e segura entre o processo principal e a página do overlay.
contextBridge.exposeInMainWorld('overlay', {
  onState: (cb) => ipcRenderer.on('state', (_e, state) => cb(state)),
  onStatus: (cb) => ipcRenderer.on('status', (_e, status) => cb(status)),
  onClickThrough: (cb) => ipcRenderer.on('click-through', (_e, value) => cb(value)),
  ready: () => ipcRenderer.send('renderer-ready'),
  openMultisearch: (side) => ipcRenderer.invoke('open-multisearch', side),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  getGuide: (championId) => ipcRenderer.invoke('guide:get', championId),
  importBuild: (championId, what, variant = 0) => ipcRenderer.invoke('import:build', { championId, what, variant }),
  onGuideUpdated: (cb) => ipcRenderer.on('guide-updated', (_e, p) => cb(p)),
  setInteractive: (on) => ipcRenderer.send('overlay:interactive', Boolean(on)),
  winMinimize: () => ipcRenderer.invoke('win:minimize'),
  winToggleMax: () => ipcRenderer.invoke('win:toggle-max'),
  winClose: () => ipcRenderer.invoke('win:close'),
  onMaximized: (cb) => ipcRenderer.on('win:maximized', (_e, v) => cb(v)),
  getTierList: (force) => ipcRenderer.invoke('tierlist:get', force),
  onTierListUpdated: (cb) => ipcRenderer.on('tierlist-updated', () => cb()),
  getOtp: (championId) => ipcRenderer.invoke('otp:get', championId),
  onOtpUpdated: (cb) => ipcRenderer.on('otp-updated', (_e, p) => cb(p)),
  hoverChampion: (championId, kind) => ipcRenderer.invoke('champselect:hover', { championId, kind }),
  opggMatches: (force) => ipcRenderer.invoke('opgg:matches', force),
  opggReview: (id, createdAt) => ipcRenderer.invoke('opgg:review', { id, createdAt }),
  onMatchesUpdated: (cb) => ipcRenderer.on('matches-updated', () => cb()),
  listHistory: () => ipcRenderer.invoke('history:list'),
  getHistory: (id) => ipcRenderer.invoke('history:get', id),
  onPostgame: (cb) => ipcRenderer.on('postgame', (_e, r) => cb(r)),
  onSpellMark: (cb) => ipcRenderer.on('spell-mark', (_e, m) => cb(m)),
  setMatchup: (id) => ipcRenderer.invoke('matchup:set', id),
  onAutoImport: (cb) => ipcRenderer.on('auto-import', (_e, r) => cb(r)),
  getUpdate: () => ipcRenderer.invoke('update:get'),
  checkUpdate: () => ipcRenderer.invoke('update:check'),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, s) => cb(s)),
  previewOverlay: () => ipcRenderer.invoke('overlay:preview'),
  onPreview: (cb) => ipcRenderer.on('preview', (_e, on) => cb(on)),
  getDiagnostics: () => ipcRenderer.invoke('diag:get'),
  onMoveMode: (cb) => ipcRenderer.on('move-mode', (_e, on) => cb(on)),
  toggleMoveMode: () => ipcRenderer.invoke('overlay:toggle-move'),
  openDataFolder: () => ipcRenderer.invoke('open-data-folder'),
});
